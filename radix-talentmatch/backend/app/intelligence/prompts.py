"""Prompt templates for the Company Intelligence pipeline — Level-4 canonical.

Verbatim ports of the Session Materials' four prompts (research / consolidation
/ expectation_matrix / hiring), token-filled with simple {{TOKEN}} replacement
(str.format is unsafe here: the prompts embed JSON braces).
"""
from __future__ import annotations

from app.intelligence.golden_record import SCHEMA_TABLE

HIERING_SKILL_REFERENCE = "DSA, COD, OOD, APTI, COMM, AI, CLOUD, SQL, SWE, SYSD, NETW, OS"


def _fill(template: str, **tokens) -> str:
    for key, value in tokens.items():
        template = template.replace("{{" + key.upper() + "}}", str(value))
    return template


# ---------------------------------------------------------------- research ----
RESEARCH_TEMPLATE = """# ROLE ASSIGNMENT
You are an expert Corporate Intelligence Analyst and Data Researcher. Your task is to conduct comprehensive web research to generate a detailed data profile for a specific target company.

# INPUT DATA
You will be provided with two things:
1. **Target Company:** The name of the entity to research.
2. **Data Schema:** A table containing parameters, definitions, types, and logic rules.

# LOGIC & FORMATTING RULES (CRITICAL)
You must adhere to the following logic strictly for every row in the Data Schema:
1. **Research & Accuracy:**
  - Search the web for current, accurate information.
  - If exact data is unavailable, provide a professional **estimate** based on industry benchmarks or similar companies.
  - Never leave a field blank. If absolutely no data or estimate is possible, write "Not Found".
2. **Atomic vs. Composite Fields (Column "A/C"):**
  - **IF ATOMIC:** the response must be a **single value**. Do not list multiple items.
  - **IF COMPOSITE:** generate multiple values, respecting the "Min" and "Max" columns.
    - **Format:** values separated ONLY by a semicolon (e.g., `Value 1; Value 2; Value 3`).
    - Do not use bullet points, numbering, or new lines within a cell.
3. **Output Format:**
  - Return the result as a **Markdown Table**.
  - Columns required: `ID`, `Category`, `A/C`, `Parameter`, `Research Output / Data`.
  - Keep the table copy-paste friendly for Excel.

# TARGET COMPANY
{{COMPANY}}

# DATA SCHEMA
(Read the table below line-by-line and generate the output for each ID)

ID  Category  Description  Parameter  Content Type to Generate  Composite elements - Minimum  Composite elements - Maximum  A/C
__SCHEMA__

# TASK EXECUTION
Perform the research for **{{COMPANY}}** using the Data Schema above. Generate the final output table now.
"""


def research(company: str) -> str:
    return _fill(RESEARCH_TEMPLATE.replace("__SCHEMA__", SCHEMA_TABLE), company=company)


# ----------------------------------------------------------- consolidation ----
CONSOLIDATION_TEMPLATE = """# ROLE ASSIGNMENT
You are a Data Reconciliation and Validation Engine. Your sole purpose is to process raw datasets, analyze duplicate entries, and consolidate them into a single "Golden Record" master file.

# INPUT DATA
You will be provided with a raw list of approximately 489 rows of data.
- The list consists of 163 unique parameters (IDs 1-163).
- Each unique ID appears 3 times (generated by different models).
- Columns: `ID`, `Category`, `A/C`, `Parameter`, `Research Output / Data`, `Source`

# THE OBJECTIVE
Reduce the input rows down to exactly 163 unique rows (one per ID). Review the 3 candidates for each ID and select the best one using the rules below.

# SELECTION LOGIC (ALGORITHM)
For each Unique ID (1 to 163), compare the 3 candidate rows and output ONLY the single best row:
1. **Eliminate Empty/Failed Data:** discard rows where the value is "Not Found", "N/A", "Unknown", or blank.
2. **Maximize Completeness:** between two valid responses, select the one that is more detailed, specific, or precise (while respecting the Atomic vs Composite rules).
3. **Source Validation:** keep the `Source` paired with the data you selected.
4. **Consistency:** if all 3 are identical, output one of them.

# ZERO FABRICATION POLICY
- DO NOT generate new text.
- DO NOT search the internet.
- DO NOT combine parts of different answers.
- ONLY select and return one of the existing lines provided.

# OUTPUT FORMAT
Return the consolidated table in Markdown with exactly these headers:
| ID | Category | A/C | Parameter | Research Output / Data | Source |

# INPUT DATASET
{{DATASET}}

# EXECUTION
Perform the consolidation now. Return exactly 163 rows.
"""


def consolidation(dataset: str) -> str:
    return _fill(CONSOLIDATION_TEMPLATE, dataset=dataset)


# ------------------------------------------------------ expectation matrix ----
EXPECTATION_MATRIX_TEMPLATE = """# ROLE
Act as a Technical Recruitment Analyst specializing in campus hiring standards. You audit technical interviews to map company expectations against academic proficiency scales.

# REFERENCE 1: The 12 Skill Areas (fixed columns)
coding, data_structures_and_algorithms, object_oriented_programming_and_design,
aptitude_and_problem_solving, communication_skills, ai_native_engineering,
devops_and_cloud, sql_and_design, software_engineering,
system_design_and_architecture, computer_networking, operating_system

# REFERENCE 2: Bloom's Proficiency Codes (Depth)
- **CU (Conceptual):** can define/explain concepts (Recall/Understand).
- **AP (Application):** can implement code in a standard scenario (Apply).
- **AS (Analysis & Synthesis):** can compare approaches and combine components (Analyze).
- **EV (Evaluation):** can justify decisions, judge efficiency, critique code (Evaluate).
- **CR (Creation):** can design new patterns/systems for unique constraints (Create).

# ACTION PROTOCOL (Dual-Analysis)
For each company and each of the 12 skills, produce a value `Level-Code`:
1. **Level (1-10):** the most advanced topic depth the company consistently tests.
2. **Code (CU/AP/AS/EV/CR):** how deep the questioning goes.
3. **Combine** strictly as `[Level]-[Code]` (e.g. `5-AP`, `7-EV`).

# OUTPUT
A Markdown table with these EXACT columns (first column header `companies`):
| companies | coding | data_structures_and_algorithms | object_oriented_programming_and_design | aptitude_and_problem_solving | communication_skills | ai_native_engineering | devops_and_cloud | sql_and_design | software_engineering | system_design_and_architecture | computer_networking | operating_system |

Every cell must be a single `Level-Code` token. No prose.

# TASK
Generate the expectation matrix for the following company:
{{COMPANIES}}
"""


def expectation_matrix(companies: str) -> str:
    return _fill(EXPECTATION_MATRIX_TEMPLATE, companies=companies)


